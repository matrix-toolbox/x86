PUT_PIXEL MACRO PX, PY, PC ; PUT_PIXEL AT (PX, PY) WITH COLOR=PC
        MOV AX, 0A000H
        MOV ES, AX

        MOV AX, 1803H
        MOV DX, 03CEH
        OUT DX, AX

        MOV DX, 03C4H
        MOV AL, 02H   ; MM
        OR AH, PC    ; CC
        OUT DX, AX    ; SELECTOR CCMMH : CC=COLOR CODE, MM=MAP MASK
        ; L := LINEAR_INDEX = PY*80 + PX\8
        ; => DI = L \ 8
        ;    AX = 8 - (L % 8)

        MOV AX, PY
        MOV CX, 80D
        MUL CX      ; AX = PY * 80
        MOV BX, AX

        MOV AX, PX
        MOV CL, 3
        SHR AX, CL ; AX = PX \ 8
        ADD BX, AX ; BX = PY * 80 + (PX \ 8)
        PUSH BX

        XOR DX, DX
        MOV AX, PX
        MOV CX, 8
        DIV CX       ; AX=AX\8   DX=AX%8

        SUB CX, DX
        DEC CX
        MOV BX, 1
        SHL BX, CL   ; AX = 8 - (L % 8)

        POP DI
        MOV DX, ES:DI
        OR DX, BX
        MOV ES:DI, DX
ENDM

